const industriesList = ['АПК', 'Производство', 'Строительство', 'Торговля', 'Недвижимость', 'Транспорт', 'IT', 'Добыча', 'Ремонт машин', 'Безопасность'];
const prefixes = ['ООО', 'АО', 'ИП'];
const names = ['Строй', 'Торг', 'Агро', 'Тех', 'Пром', 'Логистик', 'Ресурс', 'Групп', 'Сервис', 'Опт', 'Дон', 'Юг'];

export const companiesData = [];
let idCounter = 1;

// Генерируем компании для каждого города/района
Object.keys(cityCoords).forEach(city => {
  // Количество компаний зависит от размера города (Ростов - 80, районы - по 8)
  let count = 8;
  if (city === 'г. Ростов-на-Дону') count = 80;
  else if (city === 'г. Таганрог' || city === 'г. Шахты') count = 30;
  else if (city.includes('г. ')) count = 15;

  for (let i = 0; i < count; i++) {
    const isOur = Math.random() > 0.7; // 30% наши
    const industry = industriesList[Math.floor(Math.random() * industriesList.length)];
    const name = `${prefixes[Math.floor(Math.random() * prefixes.length)]} "${names[Math.floor(Math.random() * names.length)]}${Math.floor(Math.random() * 100)}"`;
    
    companiesData.push({
      id: idCounter++,
      name: name,
      inn: `${Math.floor(Math.random() * 9000000000) + 1000000000}`,
      industry: industry,
      city: city,
      isOur: isOur,
      revenue: Math.floor(Math.random() * 500) * 1000000 + 5000000,
      growth: Math.floor(Math.random() * 60) - 15,
    });
  }
});

// Функция добавления координат
export const getMapData = () => {
  return companiesData.map(company => {
    const coords = cityCoords[company.city] || [47.2313, 39.7233];
    // Микроскопический разброс, чтобы точки не сливались в одну
    const jitterLat = ((company.id * 13) % 100 - 50) / 8000; 
    const jitterLng = ((company.id * 17) % 100 - 50) / 8000;

    return {
      ...company,
      lat: coords[0] + jitterLat,
      lng: coords[1] + jitterLng,
    };
  });
};